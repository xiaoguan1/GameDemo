int
luaopen_crc_core(lua_State *L) {
	luaL_checkversion(L);

	luaL_Reg l[] = {
		{"ccitt_false", ccitt_false},
		{"ccitt", ccitt},
		{"modbus", modbus},	// 推荐使用

		{ NULL, NULL },
	};
	luaL_newlib(L, l);
	return 1;
}