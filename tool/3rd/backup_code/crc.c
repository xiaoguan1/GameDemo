// crc16的ccitt-false模型(输入反转：false、输出反转：false)
int ccitt_false(lua_State *L) {
	// - **步骤1**：初始化CRC寄存器（通常为0xFFFF）。
	// - **步骤2**：对每个数据字节：
	// 	 a. 取CRC寄存器的高8位与当前数据字节异或，得到一个8位索引。
	// 	 b. 用该索引从预计算的CRC表中查出一个16位值。
	// 	 c. 将CRC寄存器左移8位（相当于乘以256），然后与查表得到的16位值异或。
	// - **步骤3**：全部字节处理完后，CRC寄存器的值即为最终校验和。
	size_t t = 0;
	const char *str = luaL_checklstring(L, 1, &t);
	uint16_t crc = 0xffff;
	for (int i = 0; i < t; ++i) {
		uint8_t index = (crc >> 8) ^ (uint8_t)str[i];
		crc = (crc << 8) ^ CCITT_FALSE_TABLE[index];
	}
	lua_pushinteger(L, crc);
	return 1;
}

// crc16的ccitt模型(输入反转：true、输出反转：true)
int ccitt(lua_State *L) {
	// - **步骤1**：初始化CRC寄存器（通常为0x0000）。
	// - **步骤2**：对每个数据字节：
	// 	 a. 取CRC寄存器的高8位与当前数据字节异或，得到一个8位索引。
	// 	 b. 用该索引从预计算的CRC表中查出一个16位值。
	// 	 c. 将CRC寄存器左移8位（相当于乘以256），然后与查表得到的16位值异或。
	// - **步骤3**：全部字节处理完后，CRC寄存器的值即为最终校验和。
	size_t t = 0;
	const char *str = luaL_checklstring(L, 1, &t);
	uint16_t crc = 0x0000;
	for (int i = 0; i < t; ++i) {
		uint8_t index = crc ^ (uint8_t)str[i];
		crc = (crc >> 8) ^ CCITT_TABLE[index];
	}
	lua_pushinteger(L, crc);
	return 1;
}

// crc16的modbus模型（输入反转：true、输出反转：true）
