	size_t t = 0;
	const char *str = luaL_checklstring(L, 1, &t);
	uint16_t crc = 0xFFFF;
	for (int i = 0; i < t; ++i) {
		uint8_t index = crc ^ (uint8_t)str[i];
		crc = (crc >> 8) ^ MODBUS_TABLE[index];
	}
	lua_pushinteger(L, crc);
